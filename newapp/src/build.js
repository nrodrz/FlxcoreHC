/*
 * ITOps — build step (BT90, code audit M-40). The app is written in JSX (src/app.jsx, src/help.jsx) and compiled here,
 * before shipping, into plain JavaScript (app.js, help.js). Browsers then run no compiler, so the page policy needs no
 * 'unsafe-eval' or inline scripts. Run from the install folder:
 *     NODE_PATH=<folder with @babel/standalone 7.24.7> node src/build.js
 * The pages' script links get a ?v=<content hash> so a new build is never served from a browser cache.
 */
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const Babel = require('@babel/standalone');
const ROOT = path.resolve(__dirname, '..');
const OPTS = { presets: [['env', { targets: { chrome: '80', safari: '13', firefox: '74', edge: '80' } }], 'react'] };   // as the in-browser compile used before
const BANNER = f => '/* © 2026 Indisse-BTS. All rights reserved. Proprietary — licensed, not sold. See LICENSE.txt. */\n/* ITOps — compiled from src/' + f + ' by src/build.js. Do not edit this file: change src/' + f + ' and build again. */\n';
for (const [inp, out] of [['app.jsx', 'app.js'], ['help.jsx', 'help.js']]) {
  const src = fs.readFileSync(path.join(__dirname, inp), 'utf8');
  const code = Babel.transform(src, OPTS).code;
  fs.writeFileSync(path.join(ROOT, out), BANNER(inp) + code + '\n');
  console.log(out + ': ' + code.length + ' bytes');
}
const hash = f => crypto.createHash('sha256').update(fs.readFileSync(path.join(ROOT, f))).digest('hex').slice(0, 10);
for (const page of fs.readdirSync(ROOT).filter(f => /\.html$/.test(f))) {
  const p = path.join(ROOT, page); let s = fs.readFileSync(p, 'utf8'); const before = s;
  s = s.replace(/(<script src=")([A-Za-z0-9_\-\/.]+\.js)\?v=[^"]*(")/g, (m, a, f, b) => (/^vendor\//.test(f) || !fs.existsSync(path.join(ROOT, f))) ? m : a + f + '?v=' + hash(f) + b);
  if (s !== before) { fs.writeFileSync(p, s); console.log(page + ': script versions updated'); }
}
